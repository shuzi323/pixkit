/**
 * 从基础页派生出预设页。
 * 只改需要改的地方，其余（工具栏、拖拽区、样式、脚本）保持与基础页一致 ——
 * 这样基础页改进时，预设页自动跟着受益。
 */
export function renderPreset(baseHtml, p) {
  const path = `/tools/${p.tool}/${p.slug}/`;
  let h = baseHtml;

  h = h.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(p.title)}</title>`);
  h = h.replace(/(<meta name="description" content=")[^"]*(")/, `$1${esc(p.desc)}$2`);
  h = h.replace(/(<meta name="keywords" content=")[^"]*(")/, `$1${esc(p.keywords)}$2`);
  h = h.replace(/(<meta property="og:title" content=")[^"]*(")/, `$1${esc(p.title)}$2`);
  h = h.replace(/(<meta property="og:description" content=")[^"]*(")/, `$1${esc(p.desc)}$2`);
  h = h.replace(/(<link rel="canonical" href=")[^"]*(")/, `$1${SITE}${path}$2`);

  // h1 与它下面那句导语
  h = h.replace(/<h1>[\s\S]*?<\/h1>\s*<p>[\s\S]*?<\/p>/, `<h1>${esc(p.h1)}</h1>\n      <p>${p.lead}</p>`);

  // 面包屑：首页 / 基础工具 / 当前场景（给基础页留一条内链）
  h = h.replace(
    /<div class="tool-head__crumb">[\s\S]*?<\/div>/,
    `<div class="tool-head__crumb"><a href="/">首页</a> / <a href="/tools/${p.tool}/">${p.toolName}</a> / ${esc(p.crumb)}</div>`
  );

  // 引擎读这个属性来套用默认参数
  h = h.replace(/<body>/, `<body data-preset='${JSON.stringify(p.preset)}'>`);

  // 场景专属正文放在说明区最前面
  h = h.replace(/(<div class="prose"[^>]*>)/, `$1${p.unique}`);

  return h;
}
